//! Device-bound identity around the sign-in protocol.
//!
//! Sign-in itself is Microsoft Entra (External ID for customers, advisers
//! and employers; Entra ID for the workforce). What is kept here is what the
//! platform adds: the devices a party has enrolled, each with a public key
//! whose private half never leaves the device's hardware keystore; proof on
//! each request that the caller holds that key; and transaction signing,
//! where a risky action is signed by the device against a challenge that
//! names exactly that action and can be used once.
//!
//! Keys are ECDSA P-256, which is what phone keystores and WebAuthn produce.

use std::collections::{BTreeMap, BTreeSet};

use base64::Engine;
use ic_core::{PartyId, Reject};
use ring::signature::{UnparsedPublicKey, ECDSA_P256_SHA256_ASN1, ECDSA_P256_SHA256_FIXED};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::staff::At;

/// How long a request proof stays acceptable either side of the server's clock.
pub const PROOF_WINDOW_SECS: i64 = 120;
/// The longest a signing challenge may live.
pub const MAX_CHALLENGE_SECS: i64 = 300;

/// How sure the platform is of who is acting.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Assurance {
    /// A valid sign-in token and nothing more.
    Token,
    /// The token, and proof of an enrolled device's key on this request.
    Device,
    /// The device signed this exact action.
    Signed,
}

/// How a device came to be trusted.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "via", rename_all = "snake_case")]
pub enum Enrolment {
    /// The party's first device, after identity verification.
    Verification { reference: String },
    /// Approved from a device already enrolled, which signed the new key.
    ExistingDevice { device: String, signature: String },
    /// Every earlier device is lost or out of reach. After fresh identity
    /// verification this one replaces them: they are revoked, and every
    /// session the person had is closed.
    Recovery { reference: String },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Device {
    pub id: String,
    pub party: PartyId,
    /// The public key: base64 of the uncompressed SEC1 point.
    pub public_key: String,
    pub hardware_backed: bool,
    pub enrolment: Enrolment,
    pub enrolled: At,
    pub revoked: Option<At>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Challenge {
    pub id: String,
    pub device: String,
    /// SHA-256 of the canonical action being signed, in hex.
    pub action_hash: String,
    pub nonce: String,
    pub expires: At,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum IdentityCommand {
    EnrolDevice {
        device: String,
        party: PartyId,
        public_key: String,
        hardware_backed: bool,
        enrolment: Enrolment,
    },
    /// Lost, replaced or signed out. The device must wipe its local data.
    RevokeDevice { device: String },
    /// Close every session a party has, everywhere, now.
    RevokeSessions { party: PartyId },
    /// Ask a device to sign one action. The nonce is generated by the proposer.
    IssueChallenge {
        id: String,
        device: String,
        action_hash: String,
        nonce: String,
        ttl_secs: i64,
    },
    /// Present the device's signature. A challenge is consumed by its first valid use.
    RedeemChallenge { id: String, action_hash: String, signature: String },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum IdentityEvent {
    DeviceEnrolled {
        device: String,
        party: PartyId,
    },
    /// The device purges its database and outbox.
    DeviceRevoked {
        device: String,
        party: PartyId,
    },
    SessionsRevoked {
        party: PartyId,
    },
    ChallengeIssued {
        challenge: Challenge,
    },
    /// The action was signed by this device: assurance is `Signed`.
    ActionSigned {
        device: String,
        party: PartyId,
        action_hash: String,
    },
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct IdentityState {
    pub devices: BTreeMap<String, Device>,
    pub by_party: BTreeMap<PartyId, BTreeSet<String>>,
    pub challenges: BTreeMap<String, Challenge>,
    /// Tokens issued before this time are refused for the party.
    pub sessions_revoked: BTreeMap<PartyId, At>,
}

fn reject(code: &str, message: impl Into<String>) -> Reject {
    Reject::new(code, message)
}

fn decode(b64: &str) -> Option<Vec<u8>> {
    base64::engine::general_purpose::STANDARD
        .decode(b64)
        .or_else(|_| base64::engine::general_purpose::URL_SAFE_NO_PAD.decode(b64))
        .ok()
}

/// Whether `signature` over `message` verifies under a P-256 public key.
/// Both signature encodings in use are accepted: the fixed-length form that
/// browsers produce and the ASN.1 form that phone keystores produce.
pub fn verify(public_key: &str, message: &[u8], signature: &str) -> bool {
    let (Some(key), Some(sig)) = (decode(public_key), decode(signature)) else {
        return false;
    };
    UnparsedPublicKey::new(&ECDSA_P256_SHA256_FIXED, &key).verify(message, &sig).is_ok()
        || UnparsedPublicKey::new(&ECDSA_P256_SHA256_ASN1, &key).verify(message, &sig).is_ok()
}

/// The hash a device signs for an action: SHA-256 of its canonical JSON.
pub fn action_hash(action: &serde_json::Value) -> String {
    hex::encode(Sha256::digest(action.to_string().as_bytes()))
}

/// What a device signs to prove possession on an ordinary request.
pub fn proof_message(timestamp: At, method: &str, path: &str, body: &[u8]) -> Vec<u8> {
    proof_message_hashed(timestamp, method, path, &hex::encode(Sha256::digest(body)))
}

/// As [`proof_message`], from the SHA-256 of the body in hex.
pub fn proof_message_hashed(timestamp: At, method: &str, path: &str, body_sha256: &str) -> Vec<u8> {
    format!("{timestamp}\n{method}\n{path}\n{body_sha256}").into_bytes()
}

/// What a device signs to redeem a challenge.
pub fn challenge_message(challenge: &Challenge) -> Vec<u8> {
    format!("{}\n{}\n{}", challenge.id, challenge.nonce, challenge.action_hash).into_bytes()
}

impl IdentityState {
    /// A device that is enrolled, not revoked, and belongs to the party.
    pub fn active_device(&self, device: &str, party: &PartyId) -> Option<&Device> {
        self.devices.get(device).filter(|d| &d.party == party && d.revoked.is_none())
    }

    /// Whether a token issued at `issued` is still good for the party.
    pub fn session_valid(&self, party: &PartyId, issued: At) -> bool {
        self.sessions_revoked.get(party).is_none_or(|revoked| issued > *revoked)
    }

    /// Check a request's proof of possession. `proof` is `timestamp.signature`.
    #[allow(clippy::too_many_arguments)]
    pub fn check_proof(&self, party: &PartyId, device: &str, proof: &str, now: At, method: &str, path: &str, body: &[u8]) -> bool {
        self.check_proof_hashed(party, device, proof, now, method, path, &hex::encode(Sha256::digest(body)))
    }

    /// As [`Self::check_proof`], from the SHA-256 of the body in hex.
    #[allow(clippy::too_many_arguments)]
    pub fn check_proof_hashed(&self, party: &PartyId, device: &str, proof: &str, now: At, method: &str, path: &str, body_sha256: &str) -> bool {
        let Some(d) = self.active_device(device, party) else { return false };
        let Some((ts, sig)) = proof.split_once('.') else { return false };
        let Ok(ts) = ts.parse::<At>() else { return false };
        (now - ts).abs() <= PROOF_WINDOW_SECS && verify(&d.public_key, &proof_message_hashed(ts, method, path, body_sha256), sig)
    }

    pub fn apply(&mut self, at: At, command: IdentityCommand) -> Result<Vec<IdentityEvent>, Reject> {
        // Expired challenges are dropped as time moves on. This is the one
        // change a command makes before it is validated: it depends only on
        // the command's time, so every replica makes it alike.
        self.challenges.retain(|_, c| c.expires > at);
        let mut events = Vec::new();
        match command {
            IdentityCommand::EnrolDevice {
                device,
                party,
                public_key,
                hardware_backed,
                enrolment,
            } => {
                if self.devices.contains_key(&device) {
                    return Err(reject("duplicate", "that device is already enrolled"));
                }
                if decode(&public_key).is_none_or(|k| k.len() != 65 || k[0] != 4) {
                    return Err(reject("bad_key", "the key must be an uncompressed P-256 point"));
                }
                match &enrolment {
                    Enrolment::Verification { reference } | Enrolment::Recovery { reference } if reference.trim().is_empty() => {
                        return Err(reject("unverified", "enrolment needs an identity verification reference"));
                    }
                    Enrolment::Verification { .. } => {
                        // A person who still has a device adds another from it. If they do not, it is a recovery,
                        // and the devices they no longer control must not stay enrolled beside the new one.
                        if self
                            .by_party
                            .get(&party)
                            .is_some_and(|ds| ds.iter().any(|d| self.active_device(d, &party).is_some()))
                        {
                            return Err(reject("already_enrolled", "this person has a device: approve from it, or recover"));
                        }
                    }
                    Enrolment::Recovery { .. } => {
                        let old: Vec<String> = self
                            .by_party
                            .get(&party)
                            .into_iter()
                            .flatten()
                            .filter(|d| self.active_device(d, &party).is_some())
                            .cloned()
                            .collect();
                        for id in &old {
                            if let Some(d) = self.devices.get_mut(id) {
                                d.revoked = Some(at);
                            }
                            events.push(IdentityEvent::DeviceRevoked {
                                device: id.clone(),
                                party: party.clone(),
                            });
                        }
                        self.challenges.retain(|_, c| !old.contains(&c.device));
                        self.sessions_revoked.insert(party.clone(), at);
                        events.push(IdentityEvent::SessionsRevoked { party: party.clone() });
                    }
                    Enrolment::ExistingDevice { device: approver, signature } => {
                        let approver = self
                            .active_device(approver, &party)
                            .ok_or_else(|| reject("unknown_device", "the approving device is not an active device of this party"))?;
                        let message = format!("enrol\n{device}\n{public_key}");
                        if !verify(&approver.public_key, message.as_bytes(), signature) {
                            return Err(reject("bad_signature", "the approving device did not sign this key"));
                        }
                    }
                }
                self.by_party.entry(party.clone()).or_default().insert(device.clone());
                self.devices.insert(
                    device.clone(),
                    Device {
                        id: device.clone(),
                        party: party.clone(),
                        public_key,
                        hardware_backed,
                        enrolment,
                        enrolled: at,
                        revoked: None,
                    },
                );
                events.push(IdentityEvent::DeviceEnrolled { device, party });
                Ok(events)
            }
            IdentityCommand::RevokeDevice { device } => {
                let d = self
                    .devices
                    .get_mut(&device)
                    .filter(|d| d.revoked.is_none())
                    .ok_or_else(|| reject("unknown_device", "no such active device"))?;
                d.revoked = Some(at);
                let party = d.party.clone();
                self.challenges.retain(|_, c| c.device != device);
                Ok(vec![IdentityEvent::DeviceRevoked { device, party }])
            }
            IdentityCommand::RevokeSessions { party } => {
                self.sessions_revoked.insert(party.clone(), at);
                let devices = self.by_party.get(&party).cloned().unwrap_or_default();
                self.challenges.retain(|_, c| !devices.contains(&c.device));
                Ok(vec![IdentityEvent::SessionsRevoked { party }])
            }
            IdentityCommand::IssueChallenge {
                id,
                device,
                action_hash,
                nonce,
                ttl_secs,
            } => {
                if self.challenges.contains_key(&id) {
                    return Err(reject("duplicate", "that challenge exists"));
                }
                if !self.devices.get(&device).is_some_and(|d| d.revoked.is_none()) {
                    return Err(reject("unknown_device", "no such active device"));
                }
                if nonce.len() < 16 || action_hash.len() != 64 {
                    return Err(reject("bad_challenge", "a challenge needs a nonce and the hash of one action"));
                }
                let challenge = Challenge {
                    id: id.clone(),
                    device,
                    action_hash,
                    nonce,
                    expires: at + ttl_secs.clamp(1, MAX_CHALLENGE_SECS),
                };
                self.challenges.insert(id, challenge.clone());
                Ok(vec![IdentityEvent::ChallengeIssued { challenge }])
            }
            IdentityCommand::RedeemChallenge { id, action_hash, signature } => {
                let challenge = self
                    .challenges
                    .get(&id)
                    .ok_or_else(|| reject("no_challenge", "no such challenge: it may have expired or been used"))?;
                if challenge.action_hash != action_hash {
                    return Err(reject("wrong_action", "the challenge was issued for a different action"));
                }
                let device = self
                    .devices
                    .get(&challenge.device)
                    .filter(|d| d.revoked.is_none())
                    .ok_or_else(|| reject("unknown_device", "the device is no longer enrolled"))?;
                if !verify(&device.public_key, &challenge_message(challenge), &signature) {
                    return Err(reject("bad_signature", "the device's signature does not verify"));
                }
                let event = IdentityEvent::ActionSigned {
                    device: device.id.clone(),
                    party: device.party.clone(),
                    action_hash,
                };
                self.challenges.remove(&id);
                Ok(vec![event])
            }
        }
    }
}

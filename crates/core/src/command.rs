//! Commands: the only way state changes. Every command carries an
//! idempotency key and the identity of the module that sent it.

use chrono::NaiveDate;
use ic_ledger::PartitionId;
use ic_money::{DecStr, Money};
use ic_product::{Definition, Frequency, ProductDefinition, RateTable};
use serde::{Deserialize, Serialize};

use crate::payments::PayableKind;
use crate::policy::{LayerTerms, LifeFactors, LifeKind, MemberPays, PremiumOnAvoidance, ReopenedChoice, UnwindCause};
use crate::transfer::TransferRecord;
use crate::{GroupId, LifeId, PartyId, PolicyId};

/// What goes into the log.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Envelope {
    /// Idempotency key. A duplicate returns the original result.
    pub key: String,
    /// The module sending the command. Recorded on every entry it produces.
    pub caller: String,
    /// Salt for the payload commitments of the entries this command posts.
    /// Generated by the proposer, never by a replica.
    pub salt: String,
    /// W3C trace context. Outside the hash chain.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub traceparent: Option<String>,
    pub command: Command,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LifeSpec {
    pub id: LifeId,
    pub kind: LifeKind,
    pub factors: LifeFactors,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CoverSpec {
    pub code: String,
    /// The life insured. None for formula-driven group cover.
    #[serde(default)]
    pub life: Option<LifeId>,
    #[serde(default)]
    pub sum_insured_minor: i64,
    #[serde(default)]
    pub loadings: Vec<DecStr>,
    #[serde(default)]
    pub exclusions: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IssuePolicy {
    pub policy: PolicyId,
    pub number: String,
    pub group: GroupId,
    pub policyholder: PartyId,
    pub product_code: String,
    pub inception: NaiveDate,
    pub frequency: Frequency,
    pub lives: Vec<LifeSpec>,
    pub covers: Vec<CoverSpec>,
    /// The policy was written on another system and is entering through the
    /// ordinary door, with its original inception. Only the migration load
    /// may say so, and it must.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub migrated: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "change", rename_all = "snake_case")]
pub enum MemberChange {
    Joined {
        life: LifeSpec,
        effective: NaiveDate,
    },
    Left {
        life: LifeId,
        effective: NaiveDate,
    },
    /// A change to salary, category or another rating attribute.
    Changed {
        life: LifeId,
        effective: NaiveDate,
        factors: LifeFactors,
    },
    /// Undo a leave that should not have happened: the member is back from
    /// the day they were removed, with no gap in cover, and any underwritten
    /// layer that ended with the leave is restored.
    Reinstated {
        life: LifeId,
    },
}

/// An underwritten layer above a scheme member's automatic cover.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExcessLayer {
    pub policy: PolicyId,
    pub cover: String,
    pub life: LifeId,
    pub start: NaiveDate,
    pub sum_insured_minor: i64,
    /// Underwriting terms. Sensitive: never copied into an event.
    #[serde(default)]
    pub loadings: Vec<DecStr>,
    #[serde(default)]
    pub exclusions: Vec<String>,
    /// The member agreed to the employer seeing this layer's loaded premium.
    #[serde(default)]
    pub loading_itemised: bool,
    /// What of the layer's premium the member pays for themselves. Left
    /// out, the employer pays for all of it.
    #[serde(default, skip_serializing_if = "MemberPays::is_nothing")]
    pub member_pays: MemberPays,
    /// The underwriting decision this layer comes from.
    pub reference: String,
}

/// More cover on a retail policy in force, accepted by underwriting.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UnderwrittenLayer {
    pub policy: PolicyId,
    pub cover: String,
    pub life: LifeId,
    /// The cover added, on top of what the life already has.
    pub sum_insured_minor: i64,
    /// Underwriting terms. Sensitive: never copied into an event.
    #[serde(default)]
    pub loadings: Vec<DecStr>,
    #[serde(default)]
    pub exclusions: Vec<String>,
    /// The underwriting decision this layer comes from.
    pub reference: String,
}

/// Less cover for one life on a retail policy, at the owner's request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReduceCover {
    pub policy: PolicyId,
    pub cover: String,
    pub life: LifeId,
    /// The cover the life keeps. Zero gives the cover up for this life.
    pub sum_insured_minor: i64,
}

/// New underwriting terms on cover a life already has on a retail policy.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AlteredTerms {
    pub policy: PolicyId,
    pub cover: String,
    pub life: LifeId,
    /// The terms from today. Sensitive: never copied into an event.
    #[serde(default)]
    pub loadings: Vec<DecStr>,
    #[serde(default)]
    pub exclusions: Vec<String>,
    /// The underwriting decision the terms come from.
    pub reference: String,
}

/// Underwriting's decision that a lapsed policy may be reinstated.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReinstatementTerms {
    pub policy: PolicyId,
    /// The underwriting decision.
    pub reference: String,
    /// The last day the decision can be relied on.
    pub valid_until: NaiveDate,
    /// Terms that differ from the ones the cover lapsed on, applied from
    /// the day of reinstatement. Empty: reinstated on the terms it had.
    #[serde(default)]
    pub terms: Vec<crate::policy::LayerTerms>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
// Externally tagged: internally tagged enums cannot carry 128-bit integers in JSON.
#[serde(rename_all = "snake_case")]
pub enum Command {
    // --- configuration, activated through the log ---
    ActivateProduct {
        product: Box<ProductDefinition>,
    },
    ActivateRateTable {
        table: Box<RateTable>,
    },
    ActivateDefinitions {
        definitions: Vec<Definition>,
    },
    ActivateIndexRate {
        code: String,
        effective_from: NaiveDate,
        rate: DecStr,
    },

    // --- business date ---
    /// Set once, on an empty partition.
    OpenBusinessDate {
        date: NaiveDate,
    },
    /// The cutoff. Proposed by the partition leader on schedule.
    AdvanceBusinessDate {
        to: NaiveDate,
    },
    /// End-of-day phases for a chunk of policies: anniversary, billing,
    /// earning for the closed day, and arrears. Idempotent by policy and date.
    RunEndOfDay {
        policies: Vec<PolicyId>,
    },

    // --- policy lifecycle ---
    IssuePolicy(Box<IssuePolicy>),
    /// Issue on terms that were quoted: refused if the product version in
    /// force for the inception date is not the one the quote was priced on,
    /// so the terms issued are the terms offered or nothing is issued.
    IssueQuoted {
        expected_product_hash: String,
        issue: Box<IssuePolicy>,
    },
    CancelPolicy {
        policy: PolicyId,
    },
    Reinstate {
        policy: PolicyId,
    },
    DeclineIndexation {
        policy: PolicyId,
        declined: bool,
    },
    MergeLayers {
        policy: PolicyId,
        cover: String,
    },
    /// Reverse every effective-dated change after a date: layers that started
    /// after it, covers that expired after it, anniversaries and billing.
    /// Each reversal is a new entry with the original value date and a
    /// reference to the entry it reverses; nothing is removed. The policy is
    /// then held as at the date until terminated or resumed.
    UnwindAfter {
        policy: PolicyId,
        after: NaiveDate,
        cause: UnwindCause,
        /// The claim or remediation case.
        reference: String,
    },
    /// End the hold of a remediation unwind: end-of-day replays the
    /// anniversaries and billing from the unwind date on current terms.
    ResumeAfterUnwind {
        policy: PolicyId,
        reference: String,
    },
    /// End the policy with a claim, as at the insured event. Anything that
    /// happened to the policy after the event is unwound first, cover ends
    /// with the day of the event, and premium for every later day is
    /// returned.
    /// Open a period in which choices the policyholder made on a defective
    /// notice can be made again. Sent once the corrected notice has proof
    /// of delivery. The same reference with the same terms changes nothing.
    OpenReopenWindow {
        policy: PolicyId,
        reopen_reference: String,
        /// What the notice was for: `renewal`, `lapse`, `premium_change`.
        purpose: String,
        from: NaiveDate,
        until: NaiveDate,
    },
    /// Record proof that a mandatory notice was delivered. A policy does
    /// not lapse before the earliest effect of its latest lapse notice.
    RecordNoticeDelivery {
        policy: PolicyId,
        purpose: String,
        notice: String,
        delivered_on: NaiveDate,
        earliest_effect: NaiveDate,
    },
    /// Make again a choice that was made on a defective notice. Applied by
    /// value date at the original effective date, with no fee, no
    /// underwriting and no waiting period.
    ReopenChoice {
        policy: PolicyId,
        reopen_reference: String,
        choice: ReopenedChoice,
    },
    TerminateOnClaim {
        policy: PolicyId,
        event_date: NaiveDate,
        claim: String,
        /// The premiums were paid by the person the claim is for, or from an
        /// account in that person's sole name: refunds are paid with the
        /// claim and the payment authority is cancelled.
        payer_deceased: bool,
    },

    // --- group schemes ---
    /// One chunk of a membership file.
    ApplyMembership {
        policy: PolicyId,
        changes: Vec<MemberChange>,
    },
    /// Identification at claim: link an unnamed member to a person.
    IdentifyMember {
        policy: PolicyId,
        life: LifeId,
        party: PartyId,
    },
    /// Write a member's accepted cover above the automatic amount as its own
    /// layer on the scheme's cover, billed with the scheme from its start.
    AddExcessLayer(Box<ExcessLayer>),
    /// Add cover to a retail policy in force as a new layer from today, on
    /// the terms underwriting decided. The rest of a period already billed
    /// is billed as an adjustment, due today.
    AddUnderwrittenLayer(Box<UnderwrittenLayer>),
    /// Change the underwriting terms on a life's cover from today. Each
    /// layer ends and is written again with the same sum insured, origin
    /// and rating date and the new terms; the days left of a period already
    /// billed are billed or credited as an adjustment.
    AlterUnderwrittenTerms(Box<AlteredTerms>),
    /// Record underwriting's decision on a lapsed policy. `Reinstate` needs
    /// it once the lapse has run longer than the product's evidence-free
    /// days, and applies its terms from the day of reinstatement.
    ApproveReinstatement(Box<ReinstatementTerms>),
    /// Avoid a retail policy for non-disclosure, on an approved case. The
    /// case decides whether the premiums paid are refunded or kept.
    AvoidPolicy {
        policy: PolicyId,
        case: String,
        premium: PremiumOnAvoidance,
    },
    /// Vary a retail policy's terms for non-disclosure, on an approved case:
    /// the layers read as written on these terms from their start. Nothing
    /// already billed is billed again.
    VaryForNonDisclosure {
        policy: PolicyId,
        case: String,
        terms: Vec<LayerTerms>,
    },
    /// Reduce or give up one life's cover on a retail policy from today,
    /// newest layer first, with the billed premium for the days left
    /// credited back.
    ReduceCover(Box<ReduceCover>),
    /// End an underwritten layer from a date (a reduction, or the member
    /// giving the extra cover up). A leaver's layers end with the leave.
    EndExcessLayer {
        policy: PolicyId,
        cover: String,
        layer: u32,
        effective: NaiveDate,
    },

    // --- cash ---
    /// Apply a matched receipt to a policy. Sent by the cash matching service.
    ApplyReceipt {
        policy: PolicyId,
        receipt: String,
        amount: Money,
    },
    /// A dishonour or chargeback: reverses the allocation with a new entry.
    ReverseReceipt {
        policy: PolicyId,
        receipt: String,
    },
    /// Pay a credit balance in suspense back to the policyholder.
    /// Money from a scheme member for cover the member pays for themselves.
    /// It is set against what that member owes; the rest is held as the
    /// member's credit.
    ApplyMemberReceipt {
        policy: PolicyId,
        life: LifeId,
        receipt: String,
        amount: Money,
    },
    /// Pay a scheme member's credit back to the member.
    RefundMemberCredit {
        policy: PolicyId,
        life: LifeId,
        amount: Money,
    },
    RefundSuspense {
        policy: PolicyId,
        amount: Money,
        /// Pay the refund with this claim, to the estate or the beneficiary,
        /// instead of back to the source account. Required, and only
        /// accepted, where the payer is the person the claim is for.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        with_claim: Option<String>,
    },

    // --- claims ---
    /// A command for the claims module, which lives on the policy's
    /// partition. The module decides; whatever money that moves is posted by
    /// the core in the same step, so the claim and the ledger commit or fail
    /// together.
    Claims(Box<ic_claims::Command>),
    // --- investment ---
    /// A command for the investment ledger: funds, unit prices, unit orders
    /// and their execution.
    Investment(Box<crate::invest::InvestCommand>),
    /// A lender's or assignee's interest in a policy: recorded, consented
    /// for, released.
    Interest(Box<crate::interest::InterestCommand>),
    // --- payments: money leaving through a payable ---
    /// Move a credit balance from suspense to refund payable, where it waits
    /// for a payment run. The same route rule as `RefundSuspense` applies.
    RaiseRefundPayable {
        policy: PolicyId,
        /// The payments module's ID for the refund.
        refund: String,
        amount: Money,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        with_claim: Option<String>,
    },
    /// Put a raised refund that will not be paid as raised back in suspense.
    ReleaseRefundPayable {
        policy: PolicyId,
        refund: String,
    },
    /// The bank confirmed settlement: discharge the payable from the ledger
    /// account that mirrors the bank account the money left.
    SettlePayable {
        policy: PolicyId,
        /// The payment's idempotency key: its end-to-end reference at the bank.
        payment: String,
        payable: PayableKind,
        /// The refund this pays. Required for a refund payment, and only then.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        refund: Option<String>,
        amount: Money,
        /// The payments module's code for the bank account.
        bank_account: String,
    },
    /// The bank sent a settled payment back: it is owed again.
    ReturnPayment {
        policy: PolicyId,
        payment: String,
    },

    // --- reinsurance: cessions and entries worked out beside the core ---
    /// Record the cession on a layer or member cover from a date.
    RecordCession {
        policy: PolicyId,
        cover: String,
        layer: u32,
        life: LifeId,
        from: NaiveDate,
        segments: Vec<crate::reinsurance::CessionSegment>,
    },
    /// Post one reinsurance entry: ceded premium, commission, a recoverable,
    /// a recovery due, a settlement sweep. A negative amount reverses.
    PostReinsurance {
        kind: crate::reinsurance::ReinsurancePosting,
        treaty: String,
        reinsurer: String,
        currency: ic_money::Currency,
        /// The policy the entry is for. Absent for an entry that belongs to
        /// the treaty as a whole.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        policy: Option<PolicyId>,
        amount_minor: i64,
        value_date: NaiveDate,
        reference: String,
        /// The bank account a cleared settlement moved through; only for
        /// `SettlementCleared`.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        bank_account: Option<String>,
    },

    // --- policy transfer between groups ---
    BeginTransfer {
        policy: PolicyId,
        transfer_id: String,
        target_group: GroupId,
        target_partition: PartitionId,
    },
    LandTransfer {
        record: Box<TransferRecord>,
    },
    CompleteTransfer {
        policy: PolicyId,
        transfer_id: String,
    },
    AbortTransfer {
        policy: PolicyId,
        transfer_id: String,
    },

    // --- counterparties: commission payees, reinsurers, employers, debtors ---
    /// Post one balanced entry to counterparty accounts on this partition.
    PostCounterparty(Box<crate::counterparty::CounterpartyPosting>),
}

impl Command {
    /// The modules allowed to send each command. The core accepts a command
    /// only from a module allowed to send it.
    pub fn allowed_callers(&self) -> &'static [&'static str] {
        match self {
            Command::ActivateProduct { .. } | Command::ActivateRateTable { .. } | Command::ActivateDefinitions { .. } | Command::ActivateIndexRate { .. } => {
                &["config"]
            }
            Command::OpenBusinessDate { .. } | Command::AdvanceBusinessDate { .. } => &["leader"],
            Command::RunEndOfDay { .. } => &["end-of-day"],
            // Group administration issues the retail policy of a continuation
            // option and ends a scheme that is terminated.
            // The migration load issues policies written on another system.
            Command::IssuePolicy(_) => &["new-business", "group-admin", "migration"],
            Command::IssueQuoted { .. } => &["new-business"],
            // Underwriting ends interim cover when the proposal it stood in for ends.
            Command::CancelPolicy { .. } => &["policy-servicing", "group-admin", "underwriting"],
            Command::DeclineIndexation { .. } | Command::MergeLayers { .. } => &["policy-servicing"],
            Command::Reinstate { .. } => &["policy-servicing", "collections"],
            Command::UnwindAfter { .. } | Command::ResumeAfterUnwind { .. } => &["claims", "remediation"],
            Command::OpenReopenWindow { .. } | Command::RecordNoticeDelivery { .. } => &["documents"],
            Command::ReopenChoice { .. } => &["policy-servicing", "remediation"],
            Command::TerminateOnClaim { .. } => &["claims"],
            Command::ApplyMembership { .. } => &["group-admin"],
            Command::IdentifyMember { .. } => &["group-admin", "claims"],
            Command::AddExcessLayer(_) | Command::EndExcessLayer { .. } => &["group-admin", "underwriting"],
            Command::AddUnderwrittenLayer(_)
            | Command::AlterUnderwrittenTerms(_)
            | Command::ApproveReinstatement(_)
            | Command::AvoidPolicy { .. }
            | Command::VaryForNonDisclosure { .. } => &["underwriting"],
            Command::ReduceCover(_) => &["policy-servicing"],
            Command::ApplyReceipt { .. } | Command::ReverseReceipt { .. } => &["cash-matching"],
            Command::Claims(command) => command.allowed_callers(),
            Command::Investment(command) => command.allowed_callers(),
            Command::Interest(command) => command.allowed_callers(),
            Command::RefundSuspense { .. } => &["cash-matching", "policy-servicing", "claims"],
            Command::ApplyMemberReceipt { .. } => &["cash-matching"],
            Command::RefundMemberCredit { .. } => &["cash-matching", "policy-servicing"],
            Command::RecordCession { .. } | Command::PostReinsurance { .. } => &["reinsurance"],
            Command::RaiseRefundPayable { .. } | Command::ReleaseRefundPayable { .. } | Command::SettlePayable { .. } | Command::ReturnPayment { .. } => {
                &["payments"]
            }
            Command::BeginTransfer { .. } | Command::LandTransfer { .. } | Command::CompleteTransfer { .. } | Command::AbortTransfer { .. } => &["transfer"],
            Command::PostCounterparty(_) => &["distribution", "counterparty-finance"],
        }
    }

    pub fn name(&self) -> &'static str {
        match self {
            Command::ActivateProduct { .. } => "activate_product",
            Command::ActivateRateTable { .. } => "activate_rate_table",
            Command::ActivateDefinitions { .. } => "activate_definitions",
            Command::ActivateIndexRate { .. } => "activate_index_rate",
            Command::OpenBusinessDate { .. } => "open_business_date",
            Command::AdvanceBusinessDate { .. } => "advance_business_date",
            Command::RunEndOfDay { .. } => "run_end_of_day",
            Command::IssuePolicy(_) => "issue_policy",
            Command::IssueQuoted { .. } => "issue_quoted",
            Command::CancelPolicy { .. } => "cancel_policy",
            Command::Reinstate { .. } => "reinstate",
            Command::DeclineIndexation { .. } => "decline_indexation",
            Command::MergeLayers { .. } => "merge_layers",
            Command::UnwindAfter { .. } => "unwind_after",
            Command::ResumeAfterUnwind { .. } => "resume_after_unwind",
            Command::OpenReopenWindow { .. } => "open_reopen_window",
            Command::RecordNoticeDelivery { .. } => "record_notice_delivery",
            Command::ReopenChoice { .. } => "reopen_choice",
            Command::TerminateOnClaim { .. } => "terminate_on_claim",
            Command::ApplyMembership { .. } => "apply_membership",
            Command::IdentifyMember { .. } => "identify_member",
            Command::AddExcessLayer(_) => "add_excess_layer",
            Command::EndExcessLayer { .. } => "end_excess_layer",
            Command::AddUnderwrittenLayer(_) => "add_underwritten_layer",
            Command::AlterUnderwrittenTerms(_) => "alter_underwritten_terms",
            Command::ApproveReinstatement(_) => "approve_reinstatement",
            Command::AvoidPolicy { .. } => "avoid_policy",
            Command::VaryForNonDisclosure { .. } => "vary_for_non_disclosure",
            Command::ReduceCover(_) => "reduce_cover",
            Command::ApplyReceipt { .. } => "apply_receipt",
            Command::ReverseReceipt { .. } => "reverse_receipt",
            Command::RefundSuspense { .. } => "refund_suspense",
            Command::ApplyMemberReceipt { .. } => "apply_member_receipt",
            Command::RefundMemberCredit { .. } => "refund_member_credit",
            Command::Claims(_) => "claims",
            Command::Investment(_) => "investment",
            Command::Interest(_) => "interest",
            Command::RecordCession { .. } => "record_cession",
            Command::PostReinsurance { .. } => "post_reinsurance",
            Command::RaiseRefundPayable { .. } => "raise_refund_payable",
            Command::ReleaseRefundPayable { .. } => "release_refund_payable",
            Command::SettlePayable { .. } => "settle_payable",
            Command::ReturnPayment { .. } => "return_payment",
            Command::BeginTransfer { .. } => "begin_transfer",
            Command::LandTransfer { .. } => "land_transfer",
            Command::CompleteTransfer { .. } => "complete_transfer",
            Command::AbortTransfer { .. } => "abort_transfer",
            Command::PostCounterparty(_) => "post_counterparty",
        }
    }
}

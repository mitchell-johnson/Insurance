#!/usr/bin/env python3
"""Write products/definitions/aia_wordings.star from the AIA policy wordings.

Each file in products/wordings/aia/ is one AIA wording as published: a short
provenance header (title, document code and version, source, how the text
was read), a line `---`, then the text. Each becomes one definition,
`aia-wording-<file name>`, whose text is the wording itself, so a cover that
names it is bound to that exact text by its hash. The summaries in
products/definitions/aia.star say what event each cover responds to; these
are the contract text claims assesses against.

Run from the repository root:  python3 tools/aia_wordings.py
The output is committed, so a review sees every change of wording.
"""

from pathlib import Path

SOURCE = Path("products/wordings/aia")
OUT = Path("products/definitions/aia_wordings.star")
FROM = "2026-11-14"


def literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\t", " ").replace("\n", "\\n")
    return f'"{escaped}"'


def main() -> None:
    entries = []
    for f in sorted(SOURCE.glob("*.txt")):
        head, sep, body = f.read_text(encoding="utf-8").partition("\n---\n")
        if not sep or not body.strip():
            raise SystemExit(f"{f}: needs a header, a line ---, and the wording")
        meta = dict(line.split(": ", 1) for line in head.splitlines() if ": " in line)
        title = f"{meta['Document']}: {meta['Title']}"
        entries.append(f"    definition({literal('aia-wording-' + f.stem)}, 1, FROM, {literal(title)},\n               {literal(body.strip())}),")
    OUT.write_text(
        "# Generated by tools/aia_wordings.py from products/wordings/aia/. Do not edit:\n"
        "# change the wording file and run the tool. Each definition's text is an AIA\n"
        "# policy wording as published (docs/aia-products.md).\n\n"
        f'FROM = "{FROM}"\n\nDEFINITIONS = [\n' + "\n".join(entries) + "\n]\n",
        encoding="utf-8",
    )
    print(f"{len(entries)} wordings written to {OUT}")


if __name__ == "__main__":
    main()
